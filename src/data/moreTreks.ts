import { destinations, type Trek } from './treks.ts'

// Twenty real Indian treks added to the demo catalogue by `npm run seed`.
//
// Facts (district, base village, maximum altitude, usual length, season) were checked on
// 2026-11-02 against several operator itineraries and Wikipedia. Sources disagree on altitudes
// by up to a few hundred metres; the most commonly cited figure is used. The operators, prices
// and group sizes are demo values for the fictional companies in this marketplace.
//
// Photos are from Wikimedia Commons under the licence in `imageCredit`. The three treks with
// no Commons photo use the stock image of their state, and say so.

type SeedTrek = Omit<Trek, 'rating' | 'reviewCount' | 'departures'>

const commons = (path: string) => `https://upload.wikimedia.org/wikipedia/commons/${path}`
const stateImage = (state: string) => destinations.find(d => d.name === state)!.image.replace('w=400&h=300', 'w=800&h=600')

const standardInclusions = ['Trek leader and local guides', 'Tents and sleeping bags', 'All meals on the trek', 'First aid and oxygen cylinder']
const standardExclusions = ['Travel to the meeting point', 'Personal trekking gear', 'Travel insurance', 'Porter for personal bags']

function trek(t: Omit<SeedTrek, 'gallery' | 'inclusions' | 'exclusions' | 'duration'> & Partial<Pick<SeedTrek, 'inclusions' | 'exclusions'>>): SeedTrek {
  return {
    inclusions: standardInclusions,
    exclusions: standardExclusions,
    ...t,
    duration: `${t.durationDays} Days`,
    gallery: [t.image],
  }
}

